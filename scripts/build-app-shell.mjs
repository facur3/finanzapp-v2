#!/usr/bin/env node
/*
 * FinanzApp's runtime still consumes one HTML document, but the editable source
 * is intentionally split by responsibility:
 *   - src/app/index.shell.html: document/PWA boot shell
 *   - src/app/template.html: screens and presentation markup
 *   - src/app/component.js: application controller/state adapter
 *   - src/app/finanzapp.css: visual system, motion and responsive rules
 *
 * This small deterministic build step assembles index.html before Vite starts.
 * Never edit the generated index directly.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const paths = {
  shell: resolve(root, 'src/app/index.shell.html'),
  template: resolve(root, 'src/app/template.html'),
  component: resolve(root, 'src/app/component.js'),
  css: resolve(root, 'src/app/finanzapp.css'),
  cssOutput: resolve(root, 'public/finanzapp.css'),
  output: resolve(root, 'index.html'),
};

const [shell, template, component, css] = await Promise.all([
  readFile(paths.shell, 'utf8'),
  readFile(paths.template, 'utf8'),
  readFile(paths.component, 'utf8'),
  readFile(paths.css, 'utf8'),
]);

if (!shell.includes('<!-- FINANZAPP_TEMPLATE -->') || !shell.includes('/* FINANZAPP_COMPONENT */')) {
  throw new Error('FinanzApp shell markers are missing');
}

const output = shell
  // Replacer functions are intentional: component code contains `$'`/`$&`
  // sequences that String.replace would otherwise interpret as substitutions.
  .replace('<!-- FINANZAPP_TEMPLATE -->', () => template.trim())
  .replace('/* FINANZAPP_COMPONENT */', () => component.trim())
  .replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- GENERATED by scripts/build-app-shell.mjs — edit src/app/* instead. -->');

let current = '';
try { current = await readFile(paths.output, 'utf8'); } catch {}
if (current !== output) await writeFile(paths.output, output);
let currentCss = '';
try { currentCss = await readFile(paths.cssOutput, 'utf8'); } catch {}
if (currentCss !== css) await writeFile(paths.cssOutput, css);

console.log('build:app-shell — assembled index.html and public/finanzapp.css from src/app');
