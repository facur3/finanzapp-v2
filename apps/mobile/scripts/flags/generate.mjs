// npm run flags:generate -- <dir> — writes src/i18n/flag-art.ts, the round flags of every catalogue region and of the
// European Union, from circle-flags (MIT, © HatScripts; `npm pack circle-flags@2.8.3`, then pass the unpacked
// `package` directory). Each flag becomes its shapes in order, as [fill, path] pairs on a 512 square: the source's
// circle mask is dropped (the app clips the round itself) and its circles and rounded rectangles are written as paths,
// so the app draws a flag with react-native-svg's Path alone and parses nothing at runtime. Deterministic, no network.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const MOBILE = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(MOBILE, 'src', 'i18n', 'flag-art.ts');
const SOURCE = process.argv[2];
if (!SOURCE) throw new Error('Usage: npm run flags:generate -- <unpacked circle-flags package directory>');

const pkg = JSON.parse(readFileSync(join(SOURCE, 'package.json'), 'utf8'));
const license = readFileSync(join(SOURCE, 'LICENSE.md'), 'utf8').replace(/^# /, '').trim();
const { REGION_CODES } = await import(pathToFileURL(join(MOBILE, 'src', 'i18n', 'regions', 'data.ts')).href);

const attrs = text => Object.fromEntries([...text.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]));
const n = value => Number(value ?? 0);
const circle = ({ cx, cy, r }) => `M${n(cx) - n(r)} ${n(cy)}a${r} ${r} 0 1 0 ${2 * n(r)} 0a${r} ${r} 0 1 0 ${-2 * n(r)} 0z`;
function rect(a) {
  const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)];
  const rx = Math.min(n(a.rx ?? a.ry), w / 2), ry = Math.min(n(a.ry ?? a.rx), h / 2);
  if (!rx && !ry) return `M${x} ${y}h${w}v${h}h${-w}z`;
  return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-(w - 2 * rx)}`
    + `a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}z`;
}

function shapes(code) {
  const svg = readFileSync(join(SOURCE, 'flags', code.toLowerCase() + '.svg'), 'utf8');
  const body = svg.match(/<g mask="url\(#a\)">(.*)<\/g><\/svg>\s*$/s)?.[1];
  if (!body) throw new Error(`${code}: not the expected circle-flags shape`);
  return [...body.matchAll(/<(path|circle|rect)\s([^>]*?)\/?>/g)].map(([, tag, text]) => {
    const a = attrs(text);
    const extra = Object.keys(a).filter(key => !['fill', 'd', 'cx', 'cy', 'r', 'x', 'y', 'width', 'height', 'rx', 'ry'].includes(key));
    if (extra.length) throw new Error(`${code}: unsupported attribute ${extra.join(', ')}`);
    return [a.fill ?? '#000', tag === 'path' ? a.d : tag === 'circle' ? circle(a) : rect(a)];
  });
}

const codes = [...REGION_CODES, 'EU'].sort();
const lines = codes.map(code => `  ${code}: ${JSON.stringify(shapes(code))},`);
writeFileSync(OUT, `/** Generated by \`npm run flags:generate\` from circle-flags ${pkg.version} — do not edit by hand.
 * The round flag of every catalogue region and of the European Union: its shapes in drawing order, [fill, path] on a
 * 512 × 512 square, clipped to a circle by \`src/ui/marks.tsx\`.
 *
 * ${license.split('\n').join('\n * ').replace(/ \* $/gm, ' *')}
 */
export const FLAG_ART: Readonly<Record<string, readonly (readonly [string, string])[]>> = {
${lines.join('\n')}
};
`);
console.log(`flag-art.ts: ${codes.length} flags`);
